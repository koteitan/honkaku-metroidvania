for a, s, c, b in need:
    if not any(e[0] == s and e[1] == c and e[2] == b for e in byid[a]['exits']):
        errs.append(f"bible link missing {a} {s}{c} {b}")
# cross-region links must be exactly those
for r in ROOMS:
    for e in r['exits']:
        if r['id'][:2] != e[2][:2]:
            ok = any((r['id'] == a and e[2] == b) or (r['id'] == b and e[2] == a) for a, s, c, b in need)
            if not ok:
                errs.append(f"extra cross-region link {r['id']}->{e[2]}")

