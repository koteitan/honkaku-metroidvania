# ---------------- validation ----------------
byid = {r['id']: r for r in ROOMS}
occ = {}
errs = []
REG = {'WS': 'WORKSHOP', 'CL': 'CLOISTER', 'GW': 'GEARWORKS', 'NV': 'NAVE', 'GD': 'GARDEN',
       'MN': 'MINES', 'AR': 'ARCHIVE', 'SH': 'SHELL', 'CR': 'CROWN'}
for r in ROOMS:
    reg = REG[r['id'][:2]]
    for dx in range(r['w']):
        for dy in range(r['h']):
            c = (r['x'] + dx, r['y'] + dy)
            if REGION_CELLS.get(c) != reg:
                errs.append(f"{r['id']} cell {c} not in {reg} (is {REGION_CELLS.get(c)})")
            if c in occ:
                errs.append(f"overlap {c}: {occ[c]} {r['id']}")
            occ[c] = r['id']

def cells(r):
    return {(r['x'] + dx, r['y'] + dy) for dx in range(r['w']) for dy in range(r['h'])}

OPP = {'N': 'S', 'S': 'N', 'E': 'W', 'W': 'E'}
for r in ROOMS:
    for (side, c, tgt, door, gate) in r['exits']:
        if tgt not in byid:
            errs.append(f"{r['id']} -> unknown {tgt}"); continue
        t = byid[tgt]
        if side in 'EW':
            if not (r['y'] <= c < r['y'] + r['h']):
                errs.append(f"{r['id']} {side} cy{c} outside room")
            ox = r['x'] + r['w'] if side == 'E' else r['x'] - 1
            if (ox, c) not in cells(t):
                errs.append(f"{r['id']} {side} cy{c}: neighbor cell {(ox,c)} not in {tgt}")
        else:
            if not (r['x'] <= c < r['x'] + r['w']):
                errs.append(f"{r['id']} {side} cx{c} outside room")
            oy = r['y'] - 1 if side == 'N' else r['y'] + r['h']
            if (c, oy) not in cells(t):
                errs.append(f"{r['id']} {side} cx{c}: neighbor cell {(c,oy)} not in {tgt}")
        back = [e for e in t['exits'] if e[0] == OPP[side] and e[1] == c and e[2] == r['id']]
        if len(back) != 1:
            errs.append(f"{r['id']} {side}{c}->{tgt}: no reciprocal")
        elif back[0][3] != door:
            errs.append(f"{r['id']} {side}{c}->{tgt}: door mismatch {door} vs {back[0][3]}")

